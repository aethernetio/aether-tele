"""Golden block framing, record sizes and independent metric integer tiers."""
from pathlib import Path
import struct
import sys
import unittest
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
from analyze_raw import analyze
from decode_raw import CODECS, DecodeError, _encode_packed, decode


def packed(codec, value):
    base, thresholds, _ = CODECS[codec]
    return _encode_packed(value, base, thresholds)


def block(kind, fields, writers):
    out = bytes([kind]) + packed("stream", len(writers))
    if kind == 0:
        out += bytes([fields])
    for writer, body, count, base_time in writers:
        out += (packed("stream", writer) + packed("blob", len(body)) +
                packed("metric", count))
        if fields & 1:
            out += struct.pack("<Q", base_time)
        out += body
    return out


METADATA = {"tags": [{"index": 7, "level": 2, "module": 1},
                     {"index": 240, "level": 2, "module": 1}],
            "time_values_us": list(range(511)) + [60_000_000]}


class AnalysisTest(unittest.TestCase):
    def test_size_partition_and_header_amortization(self):
        # Golden bytes, independently specified rather than generated by block().
        log = b"\x00\x01\x0b\x03\x07\x01" + struct.pack("<Q", 1000) + b"\x07\x01\x01\x03abc"
        metric = b"\x01\x01\x03\x06\x01\x07\x01\x01\x05\x05\x05"
        report, rows = analyze(log + metric, METADATA)
        self.assertEqual(report["capture_bytes"], 32)
        self.assertEqual(report["log_record_bytes"], 7)
        self.assertEqual(report["payload_bytes"], 3)
        self.assertEqual(report["payload_length_bytes"], 1)
        self.assertEqual(report["log_block_header_bytes"], 14)
        self.assertEqual(report["metric_block_header_bytes"], 5)
        self.assertEqual(report["metric_bytes"], 11)
        self.assertEqual(report["time_anchor_bytes"], 0)
        self.assertEqual(report["average_log_bytes_excluding_payload"], 4)
        self.assertEqual(report["average_with_log_block_headers_excluding_payload"], 18)
        self.assertEqual(report["average_capture_bytes_excluding_payload"], 29)
        self.assertEqual(rows[0]["wire"]["offset"], 14)
        self.assertEqual(rows[1]["wire"]["offset"], 26)
        self.assertEqual(report["metrics"][7], dict(count=1, samples=1, sum=5, min=5, max=5))
        self.assertTrue(all("sequence" not in row for row in rows))

    def test_payload_length_tiers_are_overhead(self):
        for length, prefix in [(0, 1), (12, 1), (250, 1), (251, 2), (1500, 2), (1501, 4)]:
            with self.subTest(length=length):
                body = b"\x07" + packed("blob", length) + b"x" * length
                report, _ = analyze(block(0, 8, [(1, body, 1, 0)]), METADATA)
                self.assertEqual(report["payload_bytes"], length)
                self.assertEqual(report["payload_length_bytes"], prefix)
                self.assertEqual(report["average_log_bytes_excluding_payload"], 1 + prefix)

    def test_writer_ids_only_affect_headers(self):
        body = packed("tag", 240) + packed("time", 251)
        for writer in (1, 16, 1024, 65535):
            report, _ = analyze(block(0, 1, [(writer, body, 1, 1000)]), METADATA)
            self.assertEqual(report["average_log_bytes_excluding_payload"], 4)
        combined = block(0, 0, [(1, b"\x07\x07", 2, 0), (16, b"\x07", 1, 0)])
        report, rows = analyze(combined, METADATA)
        self.assertEqual(report["writer_block_count"], 2)
        self.assertEqual([row["stream"] for row in rows], [1, 1, 16])
        self.assertEqual(report["average_log_bytes_excluding_payload"], 1)

    def test_metric_tiers_are_independent_without_flags(self):
        for value, width in [(0, 1), (200, 1), (201, 2), (5000, 2),
                             (5001, 4), (100_000_000, 4),
                             (100_000_001, 8), (CODECS["metric"][2], 8)]:
            with self.subTest(value=value):
                body = b"\x07" + packed("metric", value) + b"\x01\x05\x05\x05"
                report, rows = analyze(block(1, 0, [(3, body, 1, 0)]), METADATA)
                self.assertEqual(report["metric_record_bytes"], 5 + width)
                self.assertEqual(rows[0]["metric"]["count"], value)
                self.assertIsNone(report["average_capture_bytes_excluding_payload"])

    def test_time_commands_and_restart_are_writer_local(self):
        reset = b"\x00" + struct.pack("<Q", 50)
        data = block(0, 1, [(1, b"\x07\x01" + reset + b"\x07\x01", 2, 1000),
                            (2, b"\x07\x01", 1, 5000)])
        report, rows = analyze(data, METADATA)
        self.assertEqual([row["time_us"] for row in rows], [1001, 51, 5001])
        self.assertEqual(report["time_anchor_bytes"], 9)
        self.assertEqual(report["log_bytes_excluding_payload"], 6)

    def test_empty_and_malformed_blocks(self):
        self.assertIsNone(analyze(b"", METADATA)[0]["average_log_bytes_excluding_payload"])
        good = block(0, 8, [(1, b"\x07\x03abc", 1, 0)])
        for cut in range(1, len(good)):
            with self.subTest(cut=cut), self.assertRaises(DecodeError):
                analyze(good[:cut], METADATA)
        invalid = [b"\x00\x00\x00", b"\x00\x01\x04", b"\x80\x01",
                   block(0, 0, [(1, b"\x07", 2, 0)]),
                   block(0, 0, [(1, b"\x07", 1, 0), (1, b"\x07", 1, 0)]),
                   block(0, 0, [(1, b"\x08", 1, 0)]),
                   block(0, 0, [(1, b"\x00", 1, 0)])]
        for data in invalid:
            with self.subTest(data=data), self.assertRaises(DecodeError):
                analyze(data, METADATA)
        state, stats = {17: 123}, {"block_count": 9}
        with self.assertRaises(DecodeError):
            decode(good + b"\x00", METADATA, state, wire_stats=stats)
        self.assertEqual(state, {17: 123})
        self.assertEqual(stats, {"block_count": 9})

    def test_wire_metadata_is_opt_in(self):
        row = decode(block(0, 0, [(1, b"\x07", 1, 0)]))[0][0]
        self.assertNotIn("wire", row)


if __name__ == "__main__":
    unittest.main()
